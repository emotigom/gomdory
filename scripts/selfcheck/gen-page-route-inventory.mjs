import { promises as fs } from "fs";
import path from "path";
import { fileURLToPath } from "url";

/**
 * Generates a lightweight page-route inventory that can be imported at runtime.
 *
 * Why this exists:
 * - Cloudflare Workers runtime has no filesystem access.
 * - We still want Ops tooling (broken-link bundle) to know which Next.js pages exist.
 *
 * Output:
 *   lib/generated/pageRouteInventory.ts
 */

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(SCRIPT_DIR, "../..");
const APP_DIR = path.join(REPO_ROOT, "app");
const OUT_DIR = path.join(REPO_ROOT, "lib", "generated");
const OUT_FILE = path.join(OUT_DIR, "pageRouteInventory.ts");

const IGNORED_DIRS = new Set([
  "node_modules",
  ".git",
  ".next",
  "dist",
  "out",
  "coverage",
  ".turbo",
  ".vercel",
  "public",
]);

const toPosixPath = (value) => value.split(path.sep).join("/");

const walk = async (dir, result = []) => {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (IGNORED_DIRS.has(entry.name)) continue;
      await walk(fullPath, result);
    } else if (entry.isFile()) {
      result.push(fullPath);
    }
  }
  return result;
};

const normalizeRouteSegments = (segments) => {
  const filtered = segments.filter((segment) => {
    if (!segment) return false;
    // Parallel routes / intercepting routes are not valid URL segments for our purpose
    if (segment.startsWith("@")) return false;
    // Route groups are not part of URL
    if (segment.startsWith("(") && segment.endsWith(")")) return false;
    return true;
  });
  if (filtered.length === 0) return "/";

  const normalized = filtered.map((segment) => {
    if (segment.startsWith("[[...") && segment.endsWith("]]")) {
      const name = segment.slice(5, -2);
      return `:${name}*`;
    }
    if (segment.startsWith("[...") && segment.endsWith("]")) {
      const name = segment.slice(4, -1);
      return `:${name}*`;
    }
    if (segment.startsWith("[") && segment.endsWith("]")) {
      const name = segment.slice(1, -1);
      return `:${name}`;
    }
    return segment;
  });

  return `/${normalized.join("/")}`;
};

const parseRoutePathFromPageFile = (filePath) => {
  const relative = path.relative(APP_DIR, filePath);
  const parts = toPosixPath(relative).split("/");
  const trimmed = parts.slice(0, -1); // drop page.tsx
  return normalizeRouteSegments(trimmed);
};

const compileRoutePattern = (patternPath) => {
  const normalized = patternPath === "/" ? "/" : patternPath.replace(/\/+$/, "");
  const segments = normalized === "/" ? [] : normalized.split("/").filter(Boolean);
  const compiled = segments.map((segment) => {
    if (segment.startsWith(":")) {
      const isCatchAll = segment.endsWith("*");
      return { kind: isCatchAll ? "catchall" : "param", value: segment };
    }
    return { kind: "literal", value: segment };
  });
  return { patternPath: normalized, segments: compiled };
};

const collectPageRoutePatterns = async () => {
  const files = await walk(APP_DIR);
  const pageFiles = files.filter((filePath) => /\/page\.(ts|tsx|js|jsx|mjs|cjs)$/.test(toPosixPath(filePath)));
  const patterns = pageFiles.map(parseRoutePathFromPageFile);
  const unique = Array.from(new Set(patterns));
  unique.sort();
  return unique.map(compileRoutePattern);
};

const formatTs = (compiled) => {
  const version = new Date().toISOString();
  const payload = JSON.stringify(compiled, null, 2);
  return `// This file is generated by scripts/selfcheck/gen-page-route-inventory.mjs\n// Generated at: ${version}\n\nexport type CompiledPageRoutePattern = {\n  patternPath: string;\n  segments: Array<{ kind: \"literal\" | \"param\" | \"catchall\"; value: string }>;\n};\n\nexport const PAGE_ROUTE_PATTERNS_VERSION = ${JSON.stringify(version)} as const;\n\nexport const PAGE_ROUTE_PATTERNS: CompiledPageRoutePattern[] = ${payload} as CompiledPageRoutePattern[];\n`;
};

async function main() {
  const compiled = await collectPageRoutePatterns();
  await fs.mkdir(OUT_DIR, { recursive: true });
  await fs.writeFile(OUT_FILE, formatTs(compiled), "utf8");
  console.log(`[gen-page-routes] wrote ${path.relative(REPO_ROOT, OUT_FILE)} (${compiled.length} patterns)`);
}

main().catch((err) => {
  console.error("[gen-page-routes] failed", err);
  process.exit(1);
});
